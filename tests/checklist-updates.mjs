  await page.clock.fastForward(1000);
  assert.equal(await page.locator('.epi-digits').innerText(),'02:59');
  await page.screenshot({path:'/Users/Shared/EMS Checklist/tmp/arrest-updated-desktop.png',fullPage:true});
  await page.locator('.nav-item[data-page="intubation"]').click();
  assert.equal(await page.locator('.page-heading p').count(),0);
  const sedation=page.locator('.check-row').filter({hasText:'Provide post-intubation analgesia / sedation'});
